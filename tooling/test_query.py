from utilities import bq, utils

utils.load_secrets()
client = bq.get_client()

query = """
WITH

curr AS (

SELECT
  TABLE_LAST_UPDATED as AS_OF
, MBU
, GROUPING(MBU) as TOTAL_ROW
, COUNTIF(CONTROL_DESIGN = 'IT Dependent') as IT_DEPENDENT
, COUNTIF(CONTROL_DESIGN = 'Automated') as AUTOMATED
, COUNTIF(CONTROL_DESIGN = 'Hybrid') as HYBRID
, COUNTIF(CONTROL_DESIGN IN ('IT Dependent', 'Automated', 'Hybrid')) as TOTAL_AUTO
, COUNTIF(CONTROL_DESIGN = 'Manual') as MANUAL
, COUNT(PROCEDURE_ID) as TOTAL_CONTROLS
FROM `taw-entpayments-prod-2935.AW_COMMERCIAL_CP.CONFIG`
WHERE GRC_ACTIVE = TRUE
GROUP BY GROUPING SETS ((TABLE_LAST_UPDATED, MBU), (TABLE_LAST_UPDATED))
),

needed AS (

SELECT
  AS_OF
, CASE WHEN TOTAL_ROW = 1 THEN 'TOTAL' ELSE MBU END as MBU
, TOTAL_ROW
, IT_DEPENDENT
, AUTOMATED
, HYBRID
, TOTAL_AUTO
, MANUAL
, TOTAL_CONTROLS
, ROUND(SAFE_DIVIDE(TOTAL_AUTO, TOTAL_CONTROLS) * 100, 1) as CURR_AUTO_PCT
, CAST(CEIL(TOTAL_CONTROLS * 0.60) as INT64) as TOTAL_AUTO_AT_60_PCT
, CAST(CEIL(TOTAL_CONTROLS * 0.80) as INT64) as TOTAL_AUTO_AT_80_PCT
FROM curr
)

SELECT
  AS_OF
, MBU
, MANUAL
, IT_DEPENDENT
, AUTOMATED
, HYBRID
, TOTAL_AUTO
, TOTAL_CONTROLS
, CURR_AUTO_PCT
, CAST(GREATEST(TOTAL_AUTO_AT_60_PCT - TOTAL_AUTO, 0) as INT64) as NEEDED_FOR_60_PCT
, TOTAL_AUTO_AT_60_PCT
, CAST(GREATEST(TOTAL_AUTO_AT_80_PCT - TOTAL_AUTO, 0) as INT64) as NEEDED_FOR_80_PCT
, TOTAL_AUTO_AT_80_PCT
FROM needed
ORDER BY TOTAL_ROW, MBU
"""

results = bq.query_to_df(query, client=client)
print(results)